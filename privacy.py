import re
 
 
def redact(text: str) -> str:
    """ปิดข้อมูลส่วนตัวพื้นฐานก่อนส่งให้ API ภายนอก (ช่วยได้แค่บางส่วน ควรตรวจเองอีกครั้ง)"""
    text = re.sub(r"\b\d{1}[- ]?\d{4}[- ]?\d{5}[- ]?\d{2}[- ]?\d{1}\b", "[เลขบัตร]", text)  # เลขบัตรประชาชน 13 หลัก
    text = re.sub(r"\b0\d{1,2}[- ]?\d{3}[- ]?\d{4}\b", "[เบอร์โทร]", text)  # เบอร์โทร
    text = re.sub(r"[\w.+-]+@[\w-]+\.[\w.-]+", "[อีเมล]", text)  # อีเมล
    return text
 